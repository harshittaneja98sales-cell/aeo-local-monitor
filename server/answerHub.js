import { businessTypes } from "../src/data/mockData.js";

const OPENROUTER_CHAT_COMPLETIONS_URL =
  "https://openrouter.ai/api/v1/chat/completions";
const DEFAULT_OPENROUTER_MODEL = "openai/gpt-4.1-mini";
const ANSWER_HUB_TIMEOUT_MS = 14000;

export async function generateAnswerHub(payload = {}, env = process.env) {
  const request = normalizeAnswerHubPayload(payload);
  const fallbackHub = buildFallbackAnswerHub(request, env);
  const openRouterApiKey = getOpenRouterApiKey(env);

  if (!openRouterApiKey) return fallbackHub;

  try {
    const response = await createOpenRouterChatCompletion(env, openRouterApiKey, {
      model: env.OPENROUTER_ANSWER_MODEL || env.OPENROUTER_MODEL || DEFAULT_OPENROUTER_MODEL,
      messages: [
        {
          role: "system",
          content:
            "You generate concise local-business FAQ content for answer engines. Return strict JSON only. Do not invent unverified guarantees, prices, discounts, or license claims.",
        },
        {
          role: "user",
          content: buildAnswerHubPrompt(request),
        },
      ],
      temperature: 0.25,
      response_format: { type: "json_object" },
    });
    const parsed = parseJsonResponse(response);
    const items = normalizeGeneratedItems(parsed.items, request);

    if (items.length < 4) {
      throw new Error("OpenRouter returned too few answer hub items.");
    }

    return finalizeAnswerHub(
      {
        ...fallbackHub,
        mode: "openrouter-answer-builder",
        title:
          parsed.title ||
          `${request.profile.name || "Local business"} direct-answer hub`,
        items,
        intentSummary: buildIntentSummary(items),
        providerStatus: [
          {
            provider: "OpenRouter",
            status: "live",
            detail: "Intent questions and direct answers were generated by the live model.",
          },
        ],
      },
      request,
      env
    );
  } catch (error) {
    return {
      ...fallbackHub,
      mode: "answer-builder-fallback",
      providerStatus: [
        {
          provider: "OpenRouter",
          status: "fallback",
          detail:
            error instanceof Error
              ? error.message
              : "Live answer generation failed.",
        },
      ],
    };
  }
}

export function prepareAnswerHubForSave(answerHub = {}, payload = {}, env = process.env) {
  const request = normalizeAnswerHubPayload(payload);
  const items = normalizeGeneratedItems(answerHub.items || [], request);

  return finalizeAnswerHub(
    {
      ...answerHub,
      mode: answerHub.mode || "dashboard-edited",
      title:
        answerHub.title ||
        `${request.profile.name || "Local business"} direct-answer hub`,
      status: answerHub.status || "ready",
      items,
      intentSummary: buildIntentSummary(items),
      providerStatus: answerHub.providerStatus || [],
    },
    request,
    env
  );
}

