function finalizeAnswerHub(answerHub, request, env) {
  const profile = request.profile || {};
  const items = normalizeGeneratedItems(answerHub.items || [], request);
  const title =
    answerHub.title || `${profile.name || "Local business"} direct-answer hub`;
  const approvedItems = items.filter((item) => item.approved !== false);
  const schemaJson = buildFaqSchemaJson({ title, profile, items: approvedItems });
  const visualHtml = buildVisualHtml({ title, items: approvedItems });
  const appBaseUrl = getAppBaseUrl(env);
  const businessId = answerHub.businessId || request.businessId || "";
  const embedCode = `<script async src="${appBaseUrl}/api/entity-widget?businessId=${encodeURIComponent(
    businessId || "YOUR_BUSINESS_ID"
  )}"></script>`;

  return {
    id: answerHub.id || "",
    businessId,
    status: answerHub.status || "ready",
    title,
    mode: answerHub.mode || "local-answer-builder",
    items,
    visualHtml,
    schemaType: "FAQPage",
    schemaJson,
    embedCode,
    widgetPayload: {
      title,
      approvedCount: approvedItems.length,
      questions: approvedItems.map((item) => item.question),
    },
    intentSummary: answerHub.intentSummary || buildIntentSummary(items),
    providerStatus: answerHub.providerStatus || [],
    profileSnapshot: profile,
    generatedAt: answerHub.generatedAt || new Date().toISOString(),
  };
}

