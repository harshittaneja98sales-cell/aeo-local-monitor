function buildFallbackAnswerHub(request, env) {
  const profile = request.profile;
  const items = buildBaseItems(request).map((item, index) =>
    buildItem(item, index)
  );

  return finalizeAnswerHub(
    {
      id: "",
      businessId: request.businessId || "",
      title: `${profile.name || "Local business"} direct-answer hub`,
      status: "ready",
      mode: "local-answer-builder",
      items,
      intentSummary: buildIntentSummary(items),
      providerStatus: [
        {
          provider: "Local answer builder",
          status: "ready",
          detail: "Questions and answers were generated from saved business facts.",
        },
      ],
    },
    request,
    env
  );
}

