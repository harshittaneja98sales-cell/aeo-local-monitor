async function createOpenRouterChatCompletion(env, apiKey, request) {
  const timeoutMs = parseIntegerEnv(
    env.ANSWER_HUB_TIMEOUT_MS,
    ANSWER_HUB_TIMEOUT_MS,
    5000,
    60000
  );
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);

  try {
    const response = await fetch(OPENROUTER_CHAT_COMPLETIONS_URL, {
      method: "POST",
      headers: buildOpenRouterHeaders(env, apiKey),
      body: JSON.stringify(request),
      signal: controller.signal,
    });

    if (!response.ok) {
      const detail = await response.text();
      throw new Error(`OpenRouter HTTP ${response.status}: ${truncateText(detail, 400)}`);
    }

    return response.json();
  } catch (error) {
    if (error?.name === "AbortError") {
      throw new Error(
        `OpenRouter answer hub timed out after ${Math.round(timeoutMs / 1000)} seconds.`
      );
    }
    throw error;
  } finally {
    clearTimeout(timeout);
  }
}

function parseJsonResponse(response) {
  const content = response?.choices?.[0]?.message?.content;
  const text = Array.isArray(content)
    ? content.map((item) => item.text || item.content || "").join("\n")
    : String(content || "");
  const cleaned = text
    .trim()
    .replace(/^```json\s*/i, "")
    .replace(/^```\s*/i, "")
    .replace(/\s*```$/i, "");
  return JSON.parse(cleaned);
}

function normalizeAnswerHubPayload(payload) {
  const fallbackType =
    businessTypes.find((type) => type.id === payload.selectedBusinessType) ||
    businessTypes.find((type) => type.id === payload.businessType?.id) ||
    businessTypes[0];
  const businessType =
    payload.businessType && typeof payload.businessType === "object"
      ? { ...fallbackType, ...payload.businessType }
      : fallbackType;

  return {
    profile: payload.profile || {},
    businessId: payload.businessId || "",
    businessType,
    competitors: Array.isArray(payload.competitors) ? payload.competitors : [],
    monitoredLocations: Array.isArray(payload.monitoredLocations)
      ? payload.monitoredLocations
      : [],
    auditReport:
      payload.auditReport && typeof payload.auditReport === "object"
        ? payload.auditReport
        : null,
  };
}

function normalizeGeneratedItems(items, request) {
  const fallbackItems = buildBaseItems(request).map((item, index) =>
    buildItem(item, index)
  );
  const sourceItems = Array.isArray(items) && items.length > 0 ? items : fallbackItems;

  return sourceItems
    .map((item, index) =>
      buildItem(
        {
          intent: item.intent || fallbackItems[index]?.intent || "Direct Answer",
          question: item.question || fallbackItems[index]?.question || "",
          answer: item.answer || fallbackItems[index]?.answer || "",
          source: item.source || item.sourceReason || fallbackItems[index]?.source || "Business profile",
          targetPage: item.targetPage || fallbackItems[index]?.targetPage || "Service page",
          approved: item.approved !== false,
        },
        index
      )
    )
    .filter((item) => item.question && item.answer)
    .slice(0, 8);
}

function buildItem(item, index) {
  const answer = directAnswer(item.answer);
  return {
    id: item.id || `qa-${index + 1}-${slugify(item.question).slice(0, 36)}`,
    intent: String(item.intent || "Direct Answer").trim(),
    question: cleanSentence(item.question),
    answer,
    approved: item.approved !== false,
    source: String(item.source || "Business profile").trim(),
    targetPage: String(item.targetPage || "Service page").trim(),
    wordCount: countWords(answer),
  };
}

function buildIntentSummary(items) {
  return items.map((item) => ({
    intent: item.intent,
    question: item.question,
    source: item.source,
    approved: item.approved !== false,
  }));
}

function buildFaqSchemaJson({ title, profile, items }) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    name: title,
    about: profile?.name,
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: {
        "@type": "Answer",
        text: item.answer,
      },
    })),
  };
}

function buildVisualHtml({ title, items }) {
  const rows = items
    .map(
      (item) =>
        `  <details class="aeo-answer-hub__item">\n    <summary>${escapeHtml(
          item.question
        )}</summary>\n    <p>${escapeHtml(item.answer)}</p>\n  </details>`
    )
    .join("\n");

  return `<section class="aeo-answer-hub" aria-label="${escapeHtml(
    title
  )}">\n  <h2>${escapeHtml(title)}</h2>\n${rows}\n</section>`;
}

function getApprovedItems(answerHub) {
  return (answerHub?.items || []).filter((item) => item.approved !== false);
}

function directAnswer(value) {
  const text = cleanSentence(value);
  if (/^(yes|no|fact)[:.]/i.test(text)) return text;
  return `Fact: ${text}`;
}

function cleanSentence(value) {
  return String(value || "")
    .replace(/\s+/g, " ")
    .trim();
}

function splitCsv(value) {
  return String(value || "")
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
}

function serviceTarget(service) {
  const label = String(service || "").trim();
  return label ? `${label} service page` : "Service page";
}

function extractCity(market) {
  return String(market || "the local market").split(",")[0].trim();
}

function countWords(value) {
  return String(value || "")
    .split(/\s+/)
    .filter(Boolean).length;
}

function slugify(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function escapeHtml(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function getAppBaseUrl(env) {
  if (env.APP_BASE_URL) return env.APP_BASE_URL.replace(/\/+$/, "");
  if (env.VERCEL_PROJECT_PRODUCTION_URL) {
    return `https://${env.VERCEL_PROJECT_PRODUCTION_URL}`.replace(/\/+$/, "");
  }
  if (env.VERCEL_URL) return `https://${env.VERCEL_URL}`.replace(/\/+$/, "");
  return "https://aeo-local-monitor.vercel.app";
}

function buildOpenRouterHeaders(env, apiKey) {
  const headers = {
    authorization: `Bearer ${apiKey}`,
    "content-type": "application/json",
    "x-title": "AEO Local Monitor",
  };
  const referer = getOpenRouterReferer(env);
  if (referer) headers["http-referer"] = referer;
  return headers;
}

function getOpenRouterReferer(env) {
  if (env.OPENROUTER_SITE_URL) return env.OPENROUTER_SITE_URL;
  if (env.VERCEL_PROJECT_PRODUCTION_URL) {
    return `https://${env.VERCEL_PROJECT_PRODUCTION_URL}`;
  }
  if (env.VERCEL_URL) return `https://${env.VERCEL_URL}`;
  return "";
}

function getOpenRouterApiKey(env) {
  return env.OPENROUTER_API_KEY || env.OPENROUTER_api_KEY || "";
}

function parseIntegerEnv(value, fallback, min, max) {
  const parsed = Number.parseInt(value, 10);
  if (!Number.isFinite(parsed)) return fallback;
  return Math.min(max, Math.max(min, parsed));
}

function truncateText(value, maxLength) {
  const text = String(value || "").replace(/\s+/g, " ").trim();
  return text.length > maxLength ? `${text.slice(0, maxLength)}...` : text;
}
